const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {run,node,page,context}=require('./lead-registration.cjs');
const storage=new Map();
context.localStorage={getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value)};
run(fs.readFileSync(path.join(__dirname,'../attendance-filters.js'),'utf8'));
run(`permissionChangeIdentity('admin');
a.courses.push({name:'直播测试课程',year:'2027',term:'秋季',grade:'小二',subject:'英语',teachingFormat:'直播',courseCategory:'班课'});
a.classes.push({id:'att-live',name:'周末直播A班',course:'直播测试课程',campus:'测试校区',teacher:'授课甲',academicTeacher:'教务乙',date:'2027-09-01',time:'08:00–10:00',students:8});
a.attendance.push({classIndex:3,studentIndex:0,date:'2027-09-08',time:'08:00–10:00',session:'第2讲',status:'未考勤'});
nav('attendance')`);
for(const key of ['campus','subject','grade','teacher','format','date','time','search'])assert(page().includes(`id="attendance-filter-${key}"`));
assert(!page().includes('<th>校区</th>'));assert(!page().includes('<th>课程名称</th>'));
for(const category of ['1对1','1对N'])assert(page().includes(`disabled aria-disabled="true" title="二期开发">${category} <span class="nav-phase-badge">二期</span>`));
assert(!page().includes('全部学生'));assert(page().includes('2026年春季'));
assert(page().includes('1年级'),'grade comes from actual course');
const indices=()=>JSON.parse(run('JSON.stringify(attendanceFiltered().map(row=>row.index))'));
for(const [key,value] of [['campus','测试校区'],['subject','英语'],['grade','2'],['teacher','教务乙'],['format','直播'],['date','2027-09-08'],['time','08:00-10:00'],['search','  直播a  ']]){
  run(`attendanceSetFilter(${JSON.stringify(key)},${JSON.stringify(value)})`);assert.deepEqual(indices(),[3]);
}
assert(node('#attendance-results').innerHTML.includes('attendanceOpenClass(3)'),'class survives filtering');
run("attendanceSetFilter('teacher','授课甲')");assert.deepEqual(indices(),[3]);
run("attendanceSetFilter('subject','语文')");assert.deepEqual(indices(),[]);
assert(node('#attendance-results').innerHTML.includes('暂无符合条件'));
run('attendanceResetFilters()');assert.equal(indices().length,4);
run("attendanceSetFilter('campus','测试校区');attendanceDefaultSave();attendanceSetFilter('campus','城中校区');a.modal='attendance:0';academicRender()");
assert.equal(run('attendanceFilters().campus'),'城中校区','opening modal keeps temporary filters');
run("a.modal=null;nav('students');nav('attendance')");assert.deepEqual(indices(),[3]);
assert.equal(run('attendanceFilters().search'),'');
run("attendanceSetFilter('campus','园区校区');attendanceResetFilters()");assert.deepEqual(indices(),[3]);
run('attendanceFilterViews.clear();attendanceLastView="";academicRender()');assert.deepEqual(indices(),[3],'new view loads persisted default');
run("permissionChangeIdentity('academic');nav('attendance')");assert.equal(run('attendanceFilters().campus'),'','other account has no default');
run("permissionChangeIdentity('admin');nav('attendance')");assert.deepEqual(indices(),[3]);
run("attendanceSetFilter('campus','');attendanceDefaultSave();nav('students');nav('attendance')");assert.equal(indices().length,4,'all campuses can be saved');
run("attendanceTab('1对1')");assert.equal(run('a.attTab'),'班课');
run("a.classes[3].name='<img src=x>';academicRender()");assert(page().includes('&lt;img'));assert(!page().includes('<img src=x>'));
context.localStorage.setItem=()=>{throw Error('blocked')};
run("attendanceSetFilter('campus','测试校区');attendanceDefaultSave()");assert.equal(run('attendanceDefaultRead()'),'','failed storage does not change default');
console.log('PASS: attendance combined filters, disabled categories, metadata, stable record actions, default campus persistence/account isolation/reset and escaped content.');
