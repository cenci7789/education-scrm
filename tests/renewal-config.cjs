const assert=require('node:assert/strict');
const {run,node,json,handlers}=require('./prototype-runtime.cjs')();
run(`permissionChangeIdentity('admin');state.page='system';render();systemConfigSelect('续报配置');
 a.renewalPeriods=[];a.courses=[{id:'C1',name:'秋季数学',year:2026,term:'秋季'},{id:'C2',name:'秋季语文',year:2026,term:'秋季'},{id:'C3',name:'春季数学',year:2027,term:'春季'}];
 renewalPeriodEdit();Object.assign(renewalPeriodDraft,{year:2026,term:'秋季'});render();`);
assert(node('#view').innerHTML.includes('type="datetime-local"'));
const grades=json('renewalPeriodOptions().map(([id])=>id)');assert(grades.length>1);
assert.equal((node('#view').innerHTML.match(/onchange="renewalPeriodToggle/g)||[]).length,grades.length,'all selected still displays individual grades');
run(`renewalPeriodToggle(${JSON.stringify(grades[0])},false)`);
assert.equal(run('renewalPeriodDraft.all'),false);
assert.equal(run('renewalPeriodDraft.selected.length'),grades.length-1);
run(`renewalPeriodToggle(${JSON.stringify(grades[0])},true)`);
assert.equal(run('renewalPeriodDraft.all'),true);
run(`renewalPeriodChange('scopeType','course')`);
assert.deepEqual(json('renewalPeriodOptions().map(([id])=>id)'),['C1','C2']);
assert(node('#view').innerHTML.includes('适用秋季数学'));
assert(!node('#view').innerHTML.includes('适用春季数学'));
assert(node('#view').innerHTML.includes('id="renewal-course-filter"'));
assert(node('#view').innerHTML.includes('value="" selected>全部课程'));
run("renewalPeriodSelectCourse('C2')");
assert.equal(run('renewalPeriodDraft.all'),false);
assert.deepEqual(json('renewalPeriodDraft.selected'),['C2']);
assert(node('#view').innerHTML.includes('value="C2" selected>秋季语文'));
run("renewalPeriodSelectCourse('C3')");
assert.deepEqual(json('renewalPeriodDraft.selected'),['C2'],'cannot select a course outside original term');
run("renewalPeriodSelectCourse('')");
assert.equal(run('renewalPeriodDraft.all'),true);
assert.deepEqual(json('renewalPeriodDraft.selected'),[]);
run(`renewalPeriodChange('all',false);render();Object.assign(renewalPeriodDraft,{start:'2026-10-27T09:00',end:'2026-10-27T10:00'});renewalPeriodSave()`);
assert.equal(run('a.renewalPeriods.length'),0,'empty partial selection rejected');
run(`renewalPeriodToggle('C1',true);renewalPeriodSave()`);
assert.equal(run('a.renewalPeriods.length'),1);
assert.deepEqual(json('a.renewalPeriods[0].selected'),['C1']);
for(const [time,status] of [['08:59','未开始'],['09:00','续报期内'],['10:00','续报期内'],['10:01','已结束']]){
 assert.equal(run(`renewalPeriodStatus(a.renewalPeriods[0],'2026-10-27T${time}')`),status);
}
run(`renewalPeriodEdit(a.renewalPeriods[0].id)`);
assert.equal(run('renewalPeriodDraft.start'),'2026-10-27T09:00');
assert(node('#view').innerHTML.includes('value="2026-10-27T10:00"'));handlers();
run(`renewalPeriodChange('end','2026-10-27T08:00');renewalPeriodSave()`);
assert.equal(run('a.renewalPeriods[0].end'),'2026-10-27T10:00','reversed time on same date rejected');
run(`renewalPeriodChange('end','2026-10-27T24:00');renewalPeriodSave()`);
assert.equal(run('a.renewalPeriods[0].end'),'2026-10-27T10:00','invalid hour rejected');
run(`renewalPeriodEdit();Object.assign(renewalPeriodDraft,{year:2026,term:'秋季',scopeType:'course',all:false,selected:['C1'],start:'2026-10-27T10:00',end:'2026-10-27T11:00'});renewalPeriodSave()`);
assert.equal(run('a.renewalPeriods.length'),1,'overlap includes ending minute');
run(`renewalPeriodChange('start','2026-10-27T10:01');renewalPeriodSave()`);
assert.equal(run('a.renewalPeriods.length'),2,'separate windows on same day are allowed');
run(`a.renewalPeriods.push({id:'LEGACY',year:2026,term:'秋季',start:'2026-10-28',end:'2026-10-28',scopeType:'grade',all:true,selected:[],active:true});renewalPeriodEdit('LEGACY')`);
assert.equal(run('renewalPeriodDraft.start'),'2026-10-28T00:00');
assert.equal(run('renewalPeriodDraft.end'),'2026-10-28T23:59');
assert.equal(run(`renewalPeriodStatus(a.renewalPeriods[2],'2026-10-28T23:59')`),'续报期内');
run(`renewalPeriodEdit();Object.assign(renewalPeriodDraft,{year:2026,term:'秋季',start:'2026-10-28T12:00',end:'2026-10-28T13:00'});renewalPeriodSave()`);
assert.equal(run('a.renewalPeriods.length'),3,'new timed period conflicts with legacy whole-day period');
run(`businessRestore(JSON.parse(JSON.stringify(businessSnapshot())));systemConfigSelect('续报配置')`);
assert.equal(run('a.renewalPeriods[0].start'),'2026-10-27T09:00');
assert.deepEqual(json('a.renewalPeriods[0].selected'),['C1']);
assert(node('#view').innerHTML.includes('2026-10-27 09:00'));
console.log('PASS renewal configuration: minute boundaries, legacy whole days, overlapping windows, visible scope choices, select-all, validation and restored values.');
