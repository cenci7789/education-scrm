const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {run,node,page}=require('./lead-registration.cjs');
for(const file of ['withdraw-refund.js','refund-workflow.js','refund-call-flow.js'])run(fs.readFileSync(path.join(__dirname,'..',file),'utf8'));
run("permissionChangeIdentity('academic');a.selectedStudent=0;nav('withdraw');refundNew();a.classes[0].sessions=[{id:'cut-1',name:'第一课'},{id:'cut-2',name:'第二课'}];withdrawSelectClass(a.classes[0].id);refundSelectStop('cut-1');refundReasonInput('时间冲突');refundSubmit()");
assert.equal(run('refundCurrent().step'),1);
assert(page().includes('话务呼叫'));
assert(!page().includes('refund-result-select'));
run('refundCallStart()');assert(run('refundCallModal().includes("尚未接入话务服务")'));
run('refundCallCancel()');assert.equal(run('refundCurrent().calls.length'),0);
run("refundCallStart();refundCallFinish();refundResultChange('未接听');refundCompleteCall()");
assert.equal(run('refundCurrent().calls.length'),0,'missed call requires future follow-up');
assert.equal(node('#refund-parent-opinion').hidden,true);
assert.equal(node('#refund-followup').hidden,false);
run("refundCallField('nextTime',new Date(Date.now()+3600000).toISOString());leadRecordDraft.note='无人接听';refundCompleteCall();refundCompleteCall()");
assert.equal(run('refundCurrent().calls.length'),1,'duplicate save ignored');
assert.equal(run('refundCurrent().step'),1);
assert.equal(run('refundCurrent().calls[0].outcome'),'待确认');
assert.equal(run('refundCurrent().calls[0].connected'),false);
assert.equal(run('!!refundCurrent().destination'),false);
assert(run('refundCurrent().calls[0]===a.students[0].communications.at(-1)'));
run("refundCallStart();refundCallFinish();refundResultChange('再次沟通');refundOpinionChange('继续退费');refundCallField('method','customer');refundCallField('amount','100');refundCallField('nextTime',new Date(Date.now()+7200000).toISOString());refundCompleteCall()");
assert.equal(run('refundCurrent().step'),1,'retry stays with current operator');
assert.equal(run('refundCurrent().destination.card'),'');
assert(page().includes('refund-bank-card'));
run('refundSaveBank()');assert.equal(run('refundCurrent().destination.card'),'','blank bank data accepted');
run("refundBankField('holder','家长');refundSaveBank()");
assert.equal(run('refundCurrent().destination.holder'),'家长','partial bank data accepted');
run("refundCallStart();refundCallFinish();refundResultChange('有效沟通');refundOpinionChange('继续退费');refundCallField('method','balance');refundCompleteCall()");
assert.equal(run('refundCurrent().step'),2);
assert(!page().includes('refund-bank-card'),'balance destination hides bank module');
run("permissionChangeIdentity('teacher');nav('withdraw');refundCallStart();refundCallFinish();refundResultChange('再次沟通');refundOpinionChange('撤回申请')");
assert.equal(node('#refund-followup').hidden,true,'terminal withdrawal does not schedule another call');
run('refundCompleteCall()');
assert.equal(run('refundCurrent().closed'),'已撤回');
assert.equal(run('refundCurrent().calls.length'),4);
assert.equal(run('refundCurrent().calls.at(-1).nextTime'),'');
assert.equal(run('refundCurrent().nextCommunication'),null);
assert.equal(run('withdrawBalanceCents(a.students[0])'),0,'withdrawal does not transfer funds');
console.log('PASS: phone cancellation, conditional fields, missed/retry follow-up, shared history, duplicate save, optional bank data, balance destination and terminal withdrawal.');
