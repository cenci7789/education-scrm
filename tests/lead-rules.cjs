const assert=require('node:assert/strict');
const {run,node,page}=require('./lead-registration.cjs');
run(`permissionChangeIdentity('admin');
  const clock=Date.now(),day=86400000,hour=3600000;
  function fixture(age,due=null){return {name:'规则测试',leadId:'rule-'+Math.random(),guardian:'妈妈',phone:'13912345678',grade:'小二',subject:'数学',owner:'王敏',status:'mine',stage:'跟进中',next:due===null?'未约定':new Date(clock-due*hour).toISOString(),followupCycleAt:new Date(clock-age*day).toISOString(),history:[]}}
  leadState.leads=[fixture(15),fixture(15+1/86400000),fixture(20),fixture(10,24),fixture(10,24.001),fixture(10,72),fixture(10,72.001),fixture(21),fixture(21),fixture(21)];
  leadState.leads[7].status='cold';leadState.leads[8].stage='已报名';leadState.leads[9].status='new';
  leadEvaluateRules(clock);`);
assert.equal(run('leadState.leads[0].status'),'mine','exactly 15 days is not over 15');
assert.equal(run('leadState.leads[1].status'),'warning');
assert.equal(run('leadState.leads[2].status'),'recycle');
assert.equal(run('leadState.leads[3].status'),'mine','exactly 24 hours is not over 24');
assert.equal(run('leadState.leads[4].status'),'warning');
assert.equal(run('leadState.leads[5].status'),'warning');
assert.equal(run('leadState.leads[6].status'),'recycle');
assert.equal(run('leadState.leads[6].previousOwner'),'王敏');
assert.equal(run('leadState.leads[6].owner'),'未分配');
assert.equal(run('leadState.leads[7].status'),'cold');
assert.equal(run('leadState.leads[8].status'),'mine');
assert.equal(run('leadState.leads[9].status'),'new');
const count=run('leadState.leads[2].history.length');
run('leadEvaluateRules(clock)');assert.equal(run('leadState.leads[2].history.length'),count);
run(`leadAppendCommunication(leadState.leads[1],'未接通',[],{result:'未接通',channel:'电话',intent:'',nextTime:''});leadEvaluateRules(clock)`);
assert.equal(run('leadState.leads[1].status'),'warning','ineffective communication cannot clear warning');
run(`leadAppendCommunication(leadState.leads[1],'确认了需求',[],{result:'有效沟通',channel:'电话',intent:'中意向',nextTime:''});leadEvaluateRules()`);
assert.equal(run('leadState.leads[1].status'),'mine','effective communication clears warning');
run(`leadAppendCommunication(leadState.leads[4],'未接通但改了下次时间',[],{result:'未接通',channel:'电话',intent:'',nextTime:new Date(clock+day).toISOString()});leadEvaluateRules(clock)`);
assert.equal(run('leadState.leads[4].status'),'warning','moving a deadline without effective communication cannot evade overdue rule');
run(`leadAppendCommunication(leadState.leads[4],'已有效跟进',[],{result:'有效沟通',channel:'电话',intent:'中意向',nextTime:''});leadEvaluateRules()`);
assert.equal(run('leadState.leads[4].status'),'mine');
run(`leadAppendCommunication(leadState.leads[4],'约定新的跟进时间',[],{result:'未接通',channel:'电话',intent:'中意向',nextTime:new Date(clock+day).toISOString()})`);
assert.equal(run('leadState.leads[4].followupDeadlineAt'),run('new Date(clock+day).toISOString()'),'a resolved old deadline must not replace a new appointment');
run(`leadState.selected=2;state.page='leadManage';leadState.manageTab='回收池';leadState.modal='assign'`);
run("leadRender();leadSelectAssignee(state.staff.findIndex(p=>p.name==='王敏'));assignLead()");
assert.equal(run('leadState.leads[2].status'),'mine');assert.equal(run('leadState.leads[2].next'),'未约定');
run('leadEvaluateRules()');assert.equal(run('leadState.leads[2].status'),'mine','assignment restarts the cycle');
run(`leadState.selected=2;leadState.modal='publicPool'`);node('#lead-public-reason').value='重新安排资源';run('leadReturnPublicPool()');
assert.equal(run('leadState.leads[2].status'),'recycle');assert.equal(run('leadState.leads[2].recycleReasons[0]'),'销售主动回公海');
assert.equal(run('leadState.leads[2].history.at(-1)[0]'),'回公海');
assert(page().includes('销售主动回公海'));assert(!page().includes('15 天无新沟通记录'));
run("leadState.manageTab='预警中';render()");assert(page().includes('超过15天未有效沟通'));assert(page().includes('24小时未有效跟进'));
run(`leadState.leads=[fixture(30,80)];leadState.leads[0].lastEffectiveCommunicationAt=new Date(clock-hour).toISOString();leadEvaluateRules(clock)`);
assert.equal(run('leadState.leads[0].status'),'mine','effective followup after the deadline resolves overdue');
run(`leadState.leads=[fixture(1)];delete leadState.leads[0].followupCycleAt;leadState.leads[0].next='09-20 10:00';leadEvaluateRules(clock)`);
assert.equal(run('leadState.leads[0].status'),'mine','do not guess the year of legacy display dates');
console.log('PASS: 15d/20d/24h/72h boundaries, effective vs ineffective communication, immutable overdue deadline, recovery, recycle precedence/audit, reassignment reset, public pool, exclusions and legacy time safety.');
