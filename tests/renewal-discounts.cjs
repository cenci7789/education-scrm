const assert=require('node:assert/strict');
const {run,json,node,handlers}=require('./prototype-runtime.cjs')();
run(`permissionChangeIdentity('admin');state.page='system';render();systemConfigSelect('续报配置');a.renewalPeriods=[];a.renewalDiscounts=[];
 a.courses=[{id:'C1',name:'数学课',year:2026,term:'秋季',grade:'3年级',subject:'数学'},{id:'C2',name:'语文课',year:2026,term:'秋季',grade:'4年级',subject:'语文'}];
 renewalPeriodEdit();Object.assign(renewalPeriodDraft,{year:2026,term:'秋季',start:'2026-10-24T09:00',end:'2026-10-31T18:00'});renewalPeriodSave();`);
assert(node('#view').innerHTML.includes('续报配置分类'));
assert.equal(run('a.renewalPeriods.length'),1);
run(`renewalConfigSelect('续报优惠');renewalPeriodEdit();Object.assign(renewalPeriodDraft,{year:2026,term:'秋季',start:'2026-10-24T09:00',end:'2026-10-31T18:00',discountValue:'100'});render()`);
assert(node('#view').innerHTML.includes('续报优惠方式'));
assert(node('#view').innerHTML.includes('<span>元</span>'));handlers();
run('renewalPeriodSave()');
assert.equal(run('a.renewalDiscounts.length'),1,'discount can overlap its separate renewal period');
assert.equal(run('a.renewalPeriods.length'),1);
assert(node('#view').innerHTML.includes('减免 100 元'));
const original=json('a.renewalPeriods');
run(`renewalPeriodEdit(a.renewalDiscounts[0].id);renewalPeriodChange('discountType','percent');render()`);
assert.equal(run('renewalPeriodDraft.discountValue'),'','changing unit clears the old numeric amount');
assert(node('#view').innerHTML.includes('<span>折</span>'));
for(const invalid of ['',0,-1,10,100,'8.555']){
 run(`renewalPeriodChange('discountValue',${JSON.stringify(invalid)});renewalPeriodSave()`);
 assert.equal(run('a.renewalDiscounts[0].discountType'),'reduce');
}
run(`renewalPeriodChange('discountValue','8.5');renewalPeriodChange('scopeType','course');renewalPeriodChange('all',false);renewalPeriodToggle('C1',true);renewalPeriodSave()`);
assert.equal(run('a.renewalDiscounts[0].discountType'),'percent');
assert.deepEqual(json('a.renewalDiscounts[0].selected'),['C1']);
assert(node('#view').innerHTML.includes('打 8.5 折'));
run(`renewalConfigSelect('续报周期')`);assert(!node('#view').innerHTML.includes('打 8.5 折'));assert.deepEqual(json('a.renewalPeriods'),original);
run(`renewalConfigSelect('续报优惠');renewalPeriodEdit();Object.assign(renewalPeriodDraft,{year:2026,term:'秋季',start:'2026-10-27T12:00',end:'2026-10-28T12:00',discountValue:'50'});renewalPeriodSave()`);
assert.equal(run('a.renewalDiscounts.length'),1,'overlapping active discounts on the same scope rejected');
run(`renewalPeriodChange('scopeType','course');renewalPeriodChange('all',false);renewalPeriodToggle('C2',true);renewalPeriodSave()`);
assert.equal(run('a.renewalDiscounts.length'),2,'separate scopes allowed');
run(`renewalPeriodEdit(a.renewalDiscounts[1].id);renewalPeriodChange('discountValue','999');renewalConfigSelect('续报周期')`);
assert.equal(run('a.renewalDiscounts[1].discountValue'),'50','switching tabs discards only draft');
run(`businessRestore(JSON.parse(JSON.stringify(businessSnapshot())));renewalConfigSelect('续报优惠');renewalPeriodEdit(a.renewalDiscounts[0].id)`);
assert.equal(run('renewalPeriodDraft.discountValue'),'8.5');
assert.deepEqual(json('renewalPeriodDraft.selected'),['C1']);
run(`const legacy=businessSnapshot();delete legacy.academic.renewalDiscounts;businessRestore(legacy)`);
assert.deepEqual(json('a.renewalDiscounts'),[],'legacy snapshot initializes empty discounts');
assert.deepEqual(json('a.renewalPeriods'),original);
console.log('PASS renewal discount tabs, amount/rate validation, independent period data, shared scope picker, overlap protection, edit and persistence.');
