const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {run,page}=require('./lead-registration.cjs');
for(const file of ['withdraw-refund.js','refund-workflow.js','refund-call-flow.js'])run(fs.readFileSync(path.join(__dirname,'..',file),'utf8'));
run("permissionChangeIdentity('admin');a.selectedStudent=0;nav('withdraw');refundNew();a.classes[0].sessions=[{id:'s1',name:'第一课'},{id:'s2',name:'第二课'}];a.orders=[{studentId:a.students[0].id,paid:'200.50',items:[{classId:a.classes[0].id,tuitionCents:20050,materialCents:0,discountCents:0,dueCents:20050,sessionCount:2,startSession:1}]}];a.attendance=[];withdrawSelectClass(a.classes[0].id);refundSelectStop('s1');refundReasonInput('时间冲突');refundSubmit();refundCallStart();refundCallFinish();refundResultChange('有效沟通');refundOpinionChange('继续退费');refundCallField('method','customer');refundCompleteCall()");
assert.equal(run('refundCurrent().parentOpinion'),'继续退费');
assert(!page().includes('refund-bank-panel'),'separate bank module removed');
assert(page().indexOf('refund-facts')<page().indexOf('refund-communications'));
for(const key of ['opinion','method','amount'])assert(page().includes(`refundFactEdit('${key}')`));
assert(page().includes('refundOpenBankDetails(true)'));
assert(!page().includes("refundFactEdit('holder')"),'bank fields are grouped');
const original=run('JSON.stringify(refundCurrent().calls[0])');
const edit=(key,value)=>run(`refundFactEdit('${key}');refundFactInput(${JSON.stringify(value)});refundFactSave()`);
run("refundFactEdit('amount');refundFactInput('90');refundCallCancel()");
assert.equal(run('refundCurrent().amountCents'),10025,'cancel leaves saved value intact');
for(const invalid of ['','0','-2','100.26','1.222']){
  edit('amount',invalid);assert.equal(run('refundCurrent().amountCents'),10025);
}
edit('amount','90.25');assert.equal(run('refundCurrent().requestedAmountCents'),9025);
assert.equal(run('refundCurrent().fees.remainingFee'),10025);
edit('card','1234 5678 9012 3456');assert.equal(run('refundCurrent().destination.card'),'1234567890123456');
assert.equal(run('refundCurrent().destination.holder'),'','one field update leaves others unchanged');
edit('holder','家长甲');edit('bank','示例银行');edit('refundContact','13812345678');
assert.equal(run('refundCurrent().destination.refundContact'),'13812345678');
assert(!run('JSON.stringify(refundCurrent().audit)').includes('1234567890123456'),'audit does not expose full card');
assert.equal(run('JSON.stringify(refundCurrent().calls[0])'),original,'historical communication stays unchanged');
edit('card','bad');assert.equal(run('refundCurrent().destination.card'),'1234567890123456');
edit('card','');assert.equal(run('refundCurrent().destination.card'),'','bank fields remain optional');
edit('method','balance');assert(!page().includes('refund-bank-card'));
edit('method','customer');assert.equal(run('refundCurrent().destination.bank'),'示例银行','method edits preserve existing bank details');
run("refundFactEdit('holder');refundFactInput('未保存');refundCurrent().revision++;refundFactSave()");
assert.equal(run('refundCurrent().destination.holder'),'家长甲','stale revision cannot save');
run("refundCallCancel();refundFactEdit('holder');refundFactInput('其他人');permissionChangeIdentity('sales');refundFactSave()");
assert.equal(run('refundCurrent().destination.holder'),'家长甲','identity change cannot save');
run("permissionChangeIdentity('admin');nav('withdraw');refundCurrent().step=5;refundCurrent().approvedCents=9025;academicRender()");
edit('amount','80.25');assert.equal(run('refundCurrent().step'),3);assert.equal(run('refundCurrent().approvedCents'),null);
run("refundCurrent().step=5;refundCurrent().approvedCents=8025");edit('method','balance');assert.equal(run('refundCurrent().step'),3);
edit('opinion','撤回申请');assert.equal(run('refundCurrent().closed'),'已撤回');
assert(!page().includes("refundFactEdit('opinion')"),'closed application is read-only');
assert.equal(run('withdrawBalanceCents(a.students[0])'),0,'editing does not move funds');
assert.equal(run('JSON.stringify(refundCurrent().calls[0])'),original);
console.log('PASS: consolidated editable facts, independent saves, validation/cancel, actor/revision guards, immutable history, approval reset and withdrawal.');
