const assert=require('node:assert/strict');
const {run,page}=require('./lead-registration.cjs');
run(`permissionChangeIdentity('sales');
  leadState.leads=[{leadId:'cold-lead',name:'归档学生',guardian:'妈妈',phone:'13912345678',grade:'小二',subject:'数学',intent:'低意向',owner:'王敏',status:'cold',stage:'冷宫池',next:'已归档',closeReason:'暂不需要',closeDetails:'家长暂缓安排',history:[]}];
  trialState.requests=[{id:1,leadId:'cold-lead',status:'已排班'}];
  state.page='myLeads';leadState.mineTab='冷宫池';leadState.mineSearch='归档';render();`);
assert(page().includes('再次激活</button>'));
run('myLeadReactivate(0)');
assert.equal(run('state.page'),'myLeads');
assert.equal(run('leadState.mineTab'),'可跟进');
assert.equal(run('leadState.leads[0].owner'),'王敏');
assert.equal(run('leadState.leads[0].status'),'mine');
assert.equal(run('leadState.leads[0].stage'),'新线索');
assert.equal(run('leadMyStage(leadState.leads[0])'),'新线索');
assert.equal(run('leadMyCategory(leadState.leads[0])'),'可跟进','old trial must not override reactivation');
assert.equal(run('leadState.leads[0].next'),'未约定');
assert.equal(run('leadState.leads[0].closeDetails'),'家长暂缓安排');
assert.equal(run('trialState.requests[0].status'),'已排班','preserve previous trial record');
assert(page().includes('可跟进 <small>1</small>'));assert(page().includes('冷宫池 <small>0</small>'));
assert(!page().includes('再次激活</button>'));
assert.equal(run('leadState.leads[0].history.length'),1);
run('myLeadReactivate(0)');assert.equal(run('leadState.leads[0].history.length'),1,'duplicate click has no effect');
run("leadState.leads[0].status='cold';leadState.leads[0].stage='冷宫池';leadState.leads[0].owner='陈静';myLeadReactivate(0)");
assert.equal(run('leadState.leads[0].status'),'cold','cannot reactivate another owner’s lead');
console.log('PASS: cold-pool reactivation retains owner/history, returns as new followable lead, ignores previous trial, updates counts and guards duplicate/other owner actions.');
